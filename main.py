from src.infrastructure.soundproof_parser import SoundProofFormatError, parse_soundproof_artists
from src.infrastructure.soundproof_dump_cache import SoundProofDumpCache
from src.infrastructure.soundproof_database import SoundProofDatabase
from src.domain.classification import select_tracks_with_ai_votes
from src.infrastructure.ytmusic_library import YTMusicLibrary
from src.application.library_analyzer import analyze_library
from src.report.console_report import render_console_report
from src.report.csv_report import write_csv_report
from ytmusicapi.exceptions import YTMusicError
from pathlib import Path
import urllib.error
import argparse
import logging
import sys

DEFAULT_AUTH_FILE = Path("browser.json")
DEFAULT_OUTPUT_FILE = Path("report.csv")
DEFAULT_CACHE_DIRECTORY = "soundproof_cache"
SOUNDPROOF_CACHE_FILE_NAME = "artists.json"




def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="List the songs of your YouTube Music library whose artists are reported as AI-generated in the SoundProof community database.",
    )
    parser.add_argument(
        "-a",
        "--auth-file",
        type=Path,
        default=DEFAULT_AUTH_FILE,
        help=f"Browser headers file generated by `ytmusicapi browser` (default: {DEFAULT_AUTH_FILE}).",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_FILE,
        help=f"CSV file where the tracks having at least one artist with an AI vote are exported (default: {DEFAULT_OUTPUT_FILE}).",
    )
    parser.add_argument(
        "--cache-dir",
        type=Path,
        default=DEFAULT_CACHE_DIRECTORY,
        help=f"Directory where the SoundProof dump is cached (default: {DEFAULT_CACHE_DIRECTORY}).",
    )
    parser.add_argument(
        "-r",
        "--refresh",
        action="store_true",
        help="Download the SoundProof dump even if the cached copy is less than a day old.",
    )
    return parser


def main() -> int:
    options = build_argument_parser().parse_args()
    logging.basicConfig(level=logging.WARNING, format="%(levelname)s: %(message)s")
    # Song titles may contain characters the Windows console code page cannot encode.
    sys.stdout.reconfigure(errors="replace")
    try:
        run(options)
    except (FileNotFoundError, SoundProofFormatError, urllib.error.URLError, YTMusicError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    else:
        return 0


def run(options: argparse.Namespace) -> None:
    database = load_soundproof_database(options.cache_dir / SOUNDPROOF_CACHE_FILE_NAME, options.refresh)
    print(f"Loaded {len(database)} SoundProof artists.")
    library = YTMusicLibrary.from_browser_headers(options.auth_file)
    print("Fetching your YouTube Music library...")
    verdicts = analyze_library(library, database)
    print()
    print(render_console_report(verdicts))
    tracks_with_ai_votes = select_tracks_with_ai_votes(verdicts)
    write_csv_report(tracks_with_ai_votes, options.output)
    print()
    print(f"CSV report written to {options.output} ({len(tracks_with_ai_votes)} tracks with at least one AI vote).")


def load_soundproof_database(cache_file: Path, force_refresh: bool) -> SoundProofDatabase:
    raw_dump = SoundProofDumpCache(cache_file).load(force_refresh=force_refresh)
    return SoundProofDatabase(parse_soundproof_artists(raw_dump))


if __name__ == "__main__":
    sys.exit(main())
