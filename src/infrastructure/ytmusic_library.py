from src.domain.library_track import LibraryTrack
from ytmusicapi.exceptions import YTMusicError
from typing import Any, Protocol
from ytmusicapi import YTMusic
from pathlib import Path
import logging
import json
import re

_LOGGER = logging.getLogger(__name__)
_HEADER_NAME_PATTERN = re.compile(r"^[!#$%&'*+.^_`|~0-9A-Za-z-]+$")




class LibrarySongsClient(Protocol):
    """The subset of the ytmusicapi client this adapter relies on."""

    def get_library_songs(self, limit: int | None = 25) -> list[dict[str, Any]]: ...


class YTMusicLibrary:
    """Library source reading the songs saved in a YouTube Music account."""

    def __init__(self, client: LibrarySongsClient) -> None:
        self._client = client

    @classmethod
    def from_browser_headers(cls, auth_file: Path) -> "YTMusicLibrary":
        """Connect with the browser headers file generated by the `ytmusicapi browser` command."""
        if not auth_file.is_file():
            raise FileNotFoundError(
                f"YouTube Music authentication file not found: {auth_file}. Generate it with `ytmusicapi browser`."
            )
        else:
            return cls(YTMusic(_load_headers(auth_file)))

    def fetch_tracks(self) -> list[LibraryTrack]:
        # A None limit makes ytmusicapi follow every continuation page instead of stopping at the first 25 songs.
        raw_songs = self._request_songs()
        tracks: list[LibraryTrack] = []
        for raw_song in raw_songs:
            track = _parse_song(raw_song)
            if track is None:
                _LOGGER.warning("Skipped a library song without title: %r", raw_song)
            else:
                tracks.append(track)
        return tracks


    def _request_songs(self) -> list[dict[str, Any]]:
        try:
            return self._client.get_library_songs(limit=None)
        except json.JSONDecodeError as error:
            # YouTube answers with an HTML error page when the headers are rejected, which ytmusicapi cannot decode.
            raise YTMusicError(
                "YouTube Music rejected the request (non-JSON answer). "
                "The credentials are expired or malformed: regenerate them with `ytmusicapi browser`."
            ) from error


def sanitize_browser_headers(headers: dict[str, Any]) -> dict[str, Any]:
    """Drop the entries that are not real HTTP headers.

    Firefox's "Copy Request Headers" starts with the request line (`POST /youtubei/v1/browse?... HTTP/3`), which ytmusicapi stores as a bogus header and which makes YouTube answer HTTP 400.
    """
    sanitized_headers: dict[str, Any] = {}
    for name, value in headers.items():
        if _HEADER_NAME_PATTERN.match(name):
            sanitized_headers[name] = value
        else:
            _LOGGER.warning("Ignored an invalid header in the authentication file: %.40s...", name)
    return sanitized_headers


def _load_headers(auth_file: Path) -> dict[str, Any]:
    with auth_file.open(encoding="utf-8") as auth_stream:
        return sanitize_browser_headers(json.load(auth_stream))


def _parse_song(raw_song: dict[str, Any]) -> LibraryTrack | None:
    title = raw_song.get("title")
    if not isinstance(title, str):
        return None
    else:
        return LibraryTrack(
            video_id=_optional_string(raw_song.get("videoId")),
            title=title,
            artist_names=_parse_artist_names(raw_song.get("artists")),
            album_name=_parse_album_name(raw_song.get("album")),
        )


def _parse_artist_names(raw_artists: object) -> tuple[str, ...]:
    if not isinstance(raw_artists, list):
        return ()
    else:
        return tuple(
            artist["name"]
            for artist in raw_artists
            if isinstance(artist, dict) and isinstance(artist.get("name"), str)
        )


def _parse_album_name(raw_album: object) -> str | None:
    if isinstance(raw_album, dict):
        return _optional_string(raw_album.get("name"))
    else:
        return None


def _optional_string(value: object) -> str | None:
    if isinstance(value, str):
        return value
    else:
        return None
